import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));

export const GUIDES_DIR = path.resolve(here, "../../../skills/w2agent/references/checks");
export const OUTPUT = path.resolve(here, "../src/audit/guides.generated.ts");

const FIX_BY = ["agent", "owner", "integrate"];
const SECTIONS = [
  "Passes when",
  "Who fixes it",
  "Fix (any framework)",
  "Next.js (App Router)",
  "Pitfalls",
  "Verify",
];
const OPTIONAL_SECTIONS = ["Next.js (App Router)"];

function parseFrontMatter(name, text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!m) throw new Error(`${name}: missing front matter`);
  const fm = { id: "", checks: [], fixBy: "" };
  let list = false;
  for (const line of m[1].split(/\r?\n/)) {
    const item = line.match(/^\s+-\s+(\S+)\s*$/);
    if (list && item) {
      fm.checks.push(item[1]);
      continue;
    }
    list = false;
    const kv = line.match(/^(id|checks|fixBy):\s*(.*)$/);
    if (!kv) continue;
    if (kv[1] === "checks") list = true;
    else fm[kv[1]] = kv[2].trim();
  }
  return fm;
}

function headings(text) {
  const out = [];
  let fenced = false;
  for (const line of text.split(/\r?\n/)) {
    if (/^\s*(```|~~~)/.test(line)) fenced = !fenced;
    else if (!fenced && line.startsWith("## ")) out.push(line.slice(3).trim());
  }
  return out;
}

export function loadGuides(dir = GUIDES_DIR) {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort();
  return files.map((file) => {
    const markdown = readFileSync(path.join(dir, file), "utf8");
    const { id, checks, fixBy } = parseFrontMatter(file, markdown);
    if (id !== file.slice(0, -3)) throw new Error(`${file}: id "${id}" must equal the file name`);
    if (checks.length === 0) throw new Error(`${file}: checks is empty`);
    if (!FIX_BY.includes(fixBy)) throw new Error(`${file}: invalid fixBy "${fixBy}"`);
    const expected = headings(markdown).filter((h) => SECTIONS.includes(h));
    const want = SECTIONS.filter((s) => !OPTIONAL_SECTIONS.includes(s) || expected.includes(s));
    if (headings(markdown).join("|") !== want.join("|")) {
      throw new Error(`${file}: sections must be exactly, in order: ${want.join(", ")}`);
    }
    return { id, checks, fixBy, markdown };
  });
}

export function renderModule(guides) {
  return [
    "// Generated by scripts/gen-guides.mjs from skills/w2agent/references/checks/*.md. Do not edit.",
    'import type { FixBy } from "./types.js";',
    "",
    "export interface Guide {",
    "  id: string;",
    "  checks: string[];",
    "  fixBy: FixBy;",
    "  markdown: string;",
    "}",
    "",
    `export const GUIDES: readonly Guide[] = ${JSON.stringify(guides, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = renderModule(loadGuides());
  if (process.argv.includes("--check")) {
    if (readFileSync(OUTPUT, "utf8") !== next) {
      console.error(
        "guides.generated.ts is stale against skills/w2agent/references/checks/*.md. Run: pnpm --filter w2agent-core gen:guides",
      );
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, next);
  }
}
