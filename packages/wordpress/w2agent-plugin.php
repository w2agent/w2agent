// Only an operator-provided A2A card is served (generate it with `w2agent generate <url>
// --format agent-card --a2a-endpoint <url>`); without this file WordPress 404s the path.
define( 'W2AGENT_AGENT_CARD_FILE', plugin_dir_path( __FILE__ ) . 'data/agent-card.json' );

// ─── Helpers ─────────────────────────────────────────────────────

// The site-specific plugin generated by `w2agent integrate` defines W2AGENT_SITE_PLUGIN and
// then owns the front end. Checked at call time, so plugin load order does not matter.
function w2agent_front_end_yielded() {
    return defined( 'W2AGENT_SITE_PLUGIN' );
}

// Operator-provided data files describe one crawled site: on multisite only the main site.
function w2agent_serves_data_files() {
    return ! is_multisite() || is_main_site();
}

// Path of a root-relative endpoint under this site's home URL (handles subdirectory installs).
function w2agent_route_path( $path ) {
    $route = wp_parse_url( home_url( $path ), PHP_URL_PATH );
    return is_string( $route ) ? $route : $path;
}

function w2agent_plain_text( $html ) {
    return trim( wp_strip_all_tags( strip_shortcodes( (string) $html ) ) );
}

// ─── Content selection ───────────────────────────────────────────

function w2agent_post_types() {
    $types  = [ 'page', 'post' ];
    $custom = get_post_types( [ 'public' => true, '_builtin' => false, 'exclude_from_search' => false ], 'objects' );
    foreach ( $custom as $cpt ) {
        if ( is_post_type_viewable( $cpt ) ) {
            $types[] = $cpt->name;
        }
    }

    $filtered = apply_filters( 'w2agent_post_types', $types );
    if ( is_array( $filtered ) ) {
        $types = $filtered;
    }
    return array_values( array_unique( array_filter( $types, 'post_type_exists' ) ) );
}

function w2agent_sections() {
    $sections = [];

    foreach ( w2agent_post_types() as $type ) {
        $args = [
            'post_type'    => $type,
            'post_status'  => 'publish',
            'has_password' => false,
            'numberposts'  => in_array( $type, [ 'page', 'post' ], true ) ? 100 : 50,
        ];
        if ( $type === 'page' ) {
            $args['orderby'] = 'menu_order title';
            $args['order']   = 'ASC';
        } else {
            $args['orderby'] = 'date';
            $args['order']   = 'DESC';
        }

        $posts = [];
        foreach ( get_posts( $args ) as $item ) {
            // Owners and membership plugins can drop items with the w2agent_include_post filter.
            if ( is_post_publicly_viewable( $item ) && apply_filters( 'w2agent_include_post', true, $item ) ) {
                $posts[] = $item;
            }
        }
        if ( empty( $posts ) ) continue;

        if ( $type === 'page' ) {
            $name = 'Pages';
        } elseif ( $type === 'post' ) {
            $name = 'Posts';
        } else {
            $object = get_post_type_object( $type );
            $name   = $object ? $object->label : $type;
        }
        $sections[] = [ 'name' => $name, 'posts' => $posts ];
    }

    return $sections;
}

// ─── Dynamic llms.txt generation ─────────────────────────────────

function w2agent_render( $sections ) {
    $site_name = get_bloginfo( 'name' );
    $site_desc = get_bloginfo( 'description' );

    $output = "# {$site_name}\n\n";
    if ( $site_desc ) {
        $output .= "> {$site_desc}\n\n";
    }

    foreach ( $sections as $section ) {
        $lines = [];
        foreach ( $section['posts'] as $item ) {
            $url     = get_permalink( $item );
            $title   = $item->post_title;
            $excerpt = trim( preg_replace( '/\s+/', ' ', w2agent_plain_text( $item->post_excerpt ) ) );
            if ( $excerpt === '' ) {
                $excerpt = wp_trim_words( w2agent_plain_text( $item->post_content ), 25, '...' );
            }
            $lines[] = "- [{$title}]({$url}): {$excerpt}";
        }
        $output .= '## ' . $section['name'] . "\n\n" . implode( "\n", $lines ) . "\n\n";
    }

    return $output;
}

// One transient holds a small map of home URL hash => text, so a different host or language
// home URL gets its own entry and the cache stays bounded (newest 8 kept).
function w2agent_generate_llms_txt() {
    $key   = md5( home_url( '/' ) );
    $cache = get_transient( 'w2agent_llms_txt' );
    if ( ! is_array( $cache ) ) {
        $cache = [];
    }
    if ( isset( $cache[ $key ] ) && is_string( $cache[ $key ] ) ) {
        return $cache[ $key ];
    }

    // The cached text is shared by every visitor, so build it with no user: a membership filter
    // that checks current_user_can() must not list gated items for whoever triggers the rebuild.
    $previous_user = get_current_user_id();
    wp_set_current_user( 0 );
    try {
        $output = w2agent_render( w2agent_sections() );
    } finally {
        wp_set_current_user( $previous_user );
    }
    unset( $cache[ $key ] );
    $cache[ $key ] = $output;
    $cache = array_slice( $cache, -8, null, true );
    set_transient( 'w2agent_llms_txt', $cache, HOUR_IN_SECONDS );
    return $output;
}

// ─── Serve endpoints ─────────────────────────────────────────────

add_action( 'template_redirect', function () {
    if ( w2agent_front_end_yielded() ) return;

    $uri = isset( $_SERVER['REQUEST_URI'] ) ? parse_url( $_SERVER['REQUEST_URI'], PHP_URL_PATH ) : '';

    if ( $uri === w2agent_route_path( '/llms.txt' ) ) {
        status_header( 200 );
        header( 'Content-Type: text/plain; charset=utf-8' );
        header( 'Cache-Control: public, max-age=3600' );
        echo w2agent_generate_llms_txt();
        exit;
    }

    if ( $uri === w2agent_route_path( '/.well-known/agent-card.json' ) && w2agent_serves_data_files() && file_exists( W2AGENT_AGENT_CARD_FILE ) ) {
        status_header( 200 );
        header( 'Content-Type: application/json; charset=utf-8' );
        header( 'Cache-Control: public, max-age=3600' );
        readfile( W2AGENT_AGENT_CARD_FILE );
        exit;
    }
} );

// ─── Discovery link tag ──────────────────────────────────────────

add_action( 'wp_head', function () {
    if ( w2agent_front_end_yielded() ) return;
    echo '<link rel="alternate" type="text/markdown" href="' . esc_url( home_url( '/llms.txt' ) ) . '" title="LLMs.txt">' . "\n";
} );

// ─── Robots.txt ──────────────────────────────────────────────────

add_filter( 'robots_txt', function ( $output, $public ) {
    if ( w2agent_front_end_yielded() ) return $output;
    $rules = "User-agent: *\nAllow: " . w2agent_route_path( '/llms.txt' ) . "\n";
    return $output . "\n" . $rules;
}, 10, 2 );

// ─── Cache invalidation ──────────────────────────────────────────

function w2agent_flush_cache() {
    delete_transient( 'w2agent_llms_txt' );
}

foreach ( [ 'save_post', 'deleted_post', 'trashed_post', 'untrashed_post', 'update_option_blogname', 'update_option_blogdescription' ] as $w2agent_hook ) {
    add_action( $w2agent_hook, 'w2agent_flush_cache' );
}

// ─── Platform notifications ──────────────────────────────────────

// Notifies w2agent.dev when a post that llms.txt lists changes while published, if configured.
function w2agent_notify_platform( $post ) {
    $api_key      = get_option( 'w2agent_api_key', '' );
    $webhook_slug = get_option( 'w2agent_webhook_slug', '' );
    if ( ! $api_key || ! $webhook_slug ) return;

    $post = get_post( $post );
    if ( ! $post || wp_is_post_revision( $post ) || wp_is_post_autosave( $post ) ) return;
    if ( ! in_array( $post->post_type, w2agent_post_types(), true ) ) return;

    wp_remote_post( 'https://w2agent.dev/api/agent/webhook/' . sanitize_text_field( $webhook_slug ), [
        'headers'  => [
            'Content-Type'  => 'application/json',
            'Authorization' => 'Bearer ' . $api_key,
        ],
        'body'     => wp_json_encode( [ 'trigger' => 'wordpress', 'post_id' => $post->ID ] ),
        'blocking' => false,
    ] );
}

// Publish, update of a published post, unpublish and trash all have "publish" as the old or new status.
add_action( 'transition_post_status', function ( $new_status, $old_status, $post ) {
    if ( $new_status !== 'publish' && $old_status !== 'publish' ) return;
    w2agent_notify_platform( $post );
}, 10, 3 );

// Permanent deletion of a post that is still published (trashed posts were announced when trashed).
add_action( 'before_delete_post', function ( $post_id, $post = null ) {
    $post = $post ? $post : get_post( $post_id );
    if ( ! $post || $post->post_status !== 'publish' ) return;
    w2agent_notify_platform( $post );
}, 10, 2 );

